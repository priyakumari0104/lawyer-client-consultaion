const mongoose= require("mongoose");
const otpSchema= new mongoose.Schema({
    email:{
        type:String,
        required:true,
        lowercase:true,
        trim:true
    },
    phoneNumber:{
        type:String,
        required:true,
        trim:true
    },
    emailOtp:{
        type:String,
        required:true,
    },
    phoneOtp:{
        type:String,
        required:true
    },emailVerified:{
        type:Boolean,
        default:false
    },phoneVerified:{
        type:Boolean,
        default:true
    },
    expiresAt:{
        type:Date,
        required:true
    },
    verificationToken:{
        type:String
    }
},{timestamps:true});
module.exports=mongoose.model("OTP",otpSchema);